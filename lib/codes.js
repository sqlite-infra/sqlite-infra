// node:sqlite attaches the extended result code as `errcode`. Fall back to the
// primary code (low byte) for extended codes this table predates, and to the
// same placeholder better-sqlite3 uses when even that is unknown.
function nameOf(errcode) {
  if (!Number.isInteger(errcode)) return 'UNKNOWN_SQLITE_ERROR';
  return NAMES[errcode] || NAMES[errcode & 0xff] || `UNKNOWN_SQLITE_ERROR_${errcode}`;
}

